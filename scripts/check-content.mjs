import fs from 'node:fs';
import path from 'node:path';
const cwd=process.cwd();
const file=(rel)=>fs.readFileSync(path.join(cwd,rel),'utf8');
const content=file('content/site.ts');
const page=file('app/page.tsx');
const hero=file('components/Hero.tsx');
const header=file('components/Header.tsx');
const gallery=file('components/Gallery.tsx');
const sections=['top','story','gallery','coin','how-to-buy','community'];
const code=[page,hero,header,gallery,...['components/Story.tsx','components/TokenPanel.tsx','components/HowToBuy.tsx','components/Community.tsx'].map(file)].join('\n');
let errors=[];
for (const s of sections) if(!code.includes(`id="${s}"`)) errors.push(`Missing section anchor: #${s}`);
const allNames=Array.from(content.matchAll(/image:\s*'([^']+\.(?:jpg|png))'/g), m=>m[1]);
if(allNames.length!==12) errors.push(`Expected 12 story/gallery entries, found ${allNames.length}`);
for(const name of allNames) if(!fs.existsSync(path.join(cwd,'public/images',name))) errors.push(`Missing content image ${name}`);
if(!content.includes("tokenAddress: null")) console.log('NOTICE: Contract is no longer a placeholder; confirm official link and verify address.');
if(/https:\/\/(t\.me|x\.com|twitter\.com)\/[a-zA-Z0-9_]+/.test(content)) console.log('NOTICE: Social URLs present; verify project ownership.');
if(errors.length) { console.error(errors.join('\n')); process.exitCode=1; } else console.log('PASS: Sections, 12 stories, and asset references match.');
